def wc(t):  # words in a title (markers stripped)
    return len(re.sub(r"\[\[|\]\]", "", t or "").replace("|", " ").split())

def audio(st, p, d):
    b = []
    if st == "S1": bed = ["tension", .45]; b += [["riser_soft", 0, .4], ["impact_soft", .5, .6], ["shimmer", .55, .5]]
    elif st == "S2":
        bed = ["rw_beat", .6]; n = len(p.get("adj") or ["x"])
        b += [["impact", round(i * .47, 2), .45] for i in range(n)] + [["boom", round(n * .47, 2), .6]]
    elif st == "S3":
        bed = ["rw_beat", .6]; o = .3 + (.35 if p.get("big") else 0)
        if p.get("big"): b.append(["impact", .2, .55])
        b += [["kick", round(o + i * .235, 3), .55] for i in range(wc(p.get("title")))]
    elif st == "S4": bed = ["rw_beat", .6]; b += [["swish", .05, .6], ["swish", .15, .5], ["impact", .6, .75], ["glitch", .62, .3]]
    elif st == "S5": bed = ["bright_pad", .55]; b += ([["printer", .2, .7], ["printer", .9, .5]] if p.get("receipt") else [["whoosh_rev", .1, .5], ["thump", .68, .7]])
    elif st == "S6": bed = ["rw_beat", .5]; b += [["flap", .5, .7], ["flap", 1.1, .6], ["thump", .15, .4]]
    elif st == "S7": bed = ["lux_pad", .55]; b += [["impact_soft", .35, .6], ["shimmer", .7, .55]]
    elif st == "S8": bed = ["bright_pad", .6]; b += [["whoosh", .1, .5], ["thump", .62, .6]] + [["pop", round(1.0 + i * .15, 2), .45] for i in range(4)]
    elif st == "S9": bed = ["bright_pad", .5]; b += [["pop_soft", round(.25 + i * .42, 2), .5] for i in range(len(p.get("items") or []))]
    elif st == "S10":
        bed = ["rw_beat", .45]; n = len(p.get("floorSeq") or ["a", "b", "c"])
        b += [["tick", round(.2 + i * .22, 2), .6] for i in range(n)] + [["beep_hi", round(.3 + n * .22, 2), .5], ["whoosh_soft", round(.35 + n * .22, 2), .5]]
    elif st == "S11": bed = ["rw_beat", .55]; b += [["impact", .25, .5], ["cash", .55, .6]] + [["pop", round(1.0 + i * .38, 2), .45] for i in range(len(p.get("items") or []))]
    elif st == "S13":
        bed = ["rw_beat", .55]; n = len(p.get("photo") or [1]); slot = min(.95, (d - 2.6) / n)
        b += [["impact", round(i * slot, 2), .45] for i in range(n)] + [["whoosh", round(n * slot, 2), .5], ["impact_soft", round(n * slot + .1, 2), .55]]
    elif st == "S14": bed = ["bright_pad", .55]; b += [["whoosh", .05, .5], ["whoosh", .15, .45], ["impact", .55, .6], ["shimmer", .9, .4]]
    else: bed = ["rw_beat", .5]; b += [["impact_soft", .9, .6], ["swish", 1.3, .5]]
    if p.get("red"): b += [["tick", round(t, 2), .35] for t in [x * .5 + 1.5 for x in range(int((d - 2) / .5))]]
    b.append(["whoosh_soft", round(d - 2.0, 2), .3])
    return {"bed": bed, "cues": [c for c in b if c[1] < d - .05]}

rows = []
def S(id, style, d, **p):
    p.update(id=id, style=style, series=id[0])
    p.setdefault("foot", FOOT)
    # a middle dot next to Persian digits reads as zero: use an em dash between Persian parts
    for k, v in list(p.items()):
        if isinstance(v, str): p[k] = v.replace(" · ", " — ")
        elif isinstance(v, list): p[k] = [x.replace(" · ", " — ") if isinstance(x, str) else x for x in v]
    if id[0] == "H": p.setdefault("tagEn", "ROYAL FRIDAY")
    if id in ("A01", "A06", "A10", "B01", "C05", "H02", "H07", "L02", "L03"): p.setdefault("tagEn", "BLACK FRIDAY")
    rows.append({"tag": id, "series": id[0], "duration": d, "params": p, "audio": audio(style, p, d)})

